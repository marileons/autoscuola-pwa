"use strict";
const test=require("node:test"),a=require("node:assert/strict"),fs=require("node:fs"),A=require("../lesson-activities"),D=require("../driving-errors"),T=require("../lesson-secretary-transfer"),R=require("../lesson-reminders"),S=require("../student-archive-store");
const raw=fs.readFileSync(require("node:path").join(__dirname,"student-path-peer-transfer.test.js"),"utf8");
const fixture=raw.slice(raw.indexOf("const user="),raw.indexOf("let browser;"));
const {person,user,receiver}=new Function("A","D","T","const at=Date.UTC(2026,10,18,8);"+fixture+"return {person,user,receiver}")(A,D,T);
test("promemoria: modifica, lettura, vecchi file, nuovo ID e conservazione nello storico",async()=>{
 const student=person();
 const old=R.edit(null,"Ripassare gli specchi e la precedenza.",()=>"reminder-one");
 student.lessons[0].lessonContext=A.pathContext(student.category,student.category,student.checklist.map(x=>x.label));
 student.lessons[0].nextLessonReminder=old;
 a.equal(R.pending(student).length,1);
 a.deepEqual(R.edit(old,old.text,()=>"unused"),old);
 a.equal(R.edit(old,"Un nuovo programma",()=>"reminder-two").id,"reminder-two");
 const packet=await T.createPeer(student,student.lessons[0],user);
 const backend=S.createMemoryBackend(),store=S.createStore({backend,legacyStorage:{getItem:()=>"[]"}});
 await store.initialize();await store.replaceAll([student]);
 backend.failNext(Error("errore fittizio"));
 await a.rejects(()=>store.replaceAll([R.markRead(student,old.id)]),/fittizio/);
 a.equal(R.pending((await store.snapshot())[0]).length,1);
 await store.replaceAll([R.markRead(student,old.id)]);
 a.equal(R.pending((await store.snapshot())[0]).length,0);
 await store.replaceAll(JSON.parse(JSON.stringify([student])));
 a.equal(R.pending((await store.snapshot())[0]).length,0);
 const backup=(await store.snapshotForBackup()).students;
 const fresh=S.createStore({backend:S.createMemoryBackend(),legacyStorage:{getItem:()=>"[]"}});
 await fresh.initialize();await fresh.replaceArchive(backup);
 a.equal(R.pending((await fresh.snapshot())[0]).length,0);
 await fresh.replaceArchive([student]);
 a.equal(R.pending((await fresh.snapshot())[0]).length,0);
 const same=(await fresh.snapshot())[0];
 const preview=await T.planPeer([same],packet,null,receiver);
 a.ok(["unchanged","created","updated"].includes(preview.action));
 a.equal(R.pending(preview.students[0]).length,0);
 const later=JSON.parse(JSON.stringify(student));
 later.lessons.push({...later.lessons[0],id:"next-guide",createdAt:later.lessons[0].createdAt+86400000,nextLessonReminder:R.edit(old,"Parcheggio a pettine.",()=>"reminder-two")});
 const newPacket=await T.createPeer(later,later.lessons[1],user);
 const incoming=await T.planPeer([same],newPacket,null,receiver);
 a.equal(R.pending(incoming.students[0]).length,1);
 a.equal(R.pending(incoming.students[0])[0].reminder.id,"reminder-two");
 a.equal(incoming.students[0].lessons[0].nextLessonReminder.text,old.text);
 const sentRead=await T.createPeer(R.markRead(student,old.id),R.markRead(student,old.id).lessons[0],user);
 const readPlan=await T.planPeer([student],sentRead,null,receiver);
 let saved;
 await T.applyPeer(readPlan,{read:async()=>[student],write:async next=>saved=next},async()=>receiver);
 a.equal(R.pending(saved[0]).length,0);
});
